#!/usr/bin/env python3
"""Writes .docs/quest_guide.md: a player walkthrough of every quest, from data/quests/*.tres and the English text
tables. Re-run after changing quests or text:  python3 .docs/gen_quest_guide.py"""
import csv, glob, json, os, re
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
T = {}
for f in glob.glob('data/text/*.csv'):
    for r in csv.reader(open(f)):
        if len(r) == 3: T[r[0]] = r[2]
KEYS = {'interact': 'E', 'cast': 'Right Mouse', 'attack': 'Left Mouse', 'dodge': 'Space', 'move': 'WASD'}   # default bindings
def fmt(t): return re.sub(r'\{(\w+)\}', lambda m: KEYS.get(m.group(1), m.group(0)), t)
def zone(z): return T.get('UI_ZONE_' + z.upper(), z)
starters = {}
for f in glob.glob('data/dialogue/*.tres'):
    for q in re.findall(r'"start:(\w+)"', open(f).read()):
        starters.setdefault(q, os.path.basename(f)[:-5])
def npc(i): return T.get('NPC_%s_NAME' % i.upper(), i.replace('_', ' ').title())
order = ['mq0', 'mq1', 'mqg', 'mq2', 'mq3', 'mq4', 'mq5']
files = sorted(glob.glob('data/quests/*.tres'), key=lambda f: (os.path.basename(f)[:-5] not in order, order.index(os.path.basename(f)[:-5]) if os.path.basename(f)[:-5] in order else 0, f))
out = ['# Quest guide', '', 'Generated by `.docs/gen_quest_guide.py` from the quest data. Do not edit by hand.', '',
       'Each quest lists where it starts, then its steps in order. "Where" is the area to go to; sub-goals can be done in the order shown, and the HUD arrow always points at the next one.', '']
for f in files:
    qid = os.path.basename(f)[:-5]
    s = open(f).read()
    kind = re.search(r'^kind = "(\w+)"', s, re.M)
    zn = re.search(r'^zone = "(\w+)"', s, re.M)
    title = T.get('Q_%s_TITLE' % qid.upper(), qid)
    out += ['## ' + title, '', '- Type: %s | Region: %s' % ((kind.group(1) if kind else 'side').title(), zone(zn.group(1)) if zn else '-')]
    out.append('- Starts: ' + ('talk to %s' % npc(starters[qid]) if qid in starters else 'automatically as the story advances'))
    if 'Q_%s_DESC' % qid.upper() in T: out += ['', '> ' + T['Q_%s_DESC' % qid.upper()]]
    out.append('')
    n = 0
    for sid, b in re.findall(r'id="(\w+)"\]\n(.*?)(?=\n\[|\Z)', s, re.S):
        ob = re.search(r'^objective = "(\w+)"', b, re.M)
        if not ob: continue
        n += 1
        key = ob.group(1)
        m = re.search(r'^marker = (\{.*\})', b, re.M)
        where = zone(json.loads(m.group(1)).get('zone', '')) if m else ''
        out.append('%d. %s%s' % (n, T.get(key, key), '  \n   *Where: %s*' % where if where else ''))
        am = re.search(r'^all = (\[.*\])$', b, re.M)
        if am:
            for sb in json.loads(am.group(1)):
                out.append('   - [ ] ' + T.get(sb.get('objective', ''), sb['on']))
        hk = key.replace('_OBJ', '_HINT')
        if hk in T: out.append('   - Tip: ' + fmt(T[hk]))
    out.append('')
open('.docs/quest_guide.md', 'w').write('\n'.join(out))
print(len(files), 'quests')

"""Generate one zones/<area>.gd/.tscn per "## Area n: <id>" section (map + legend) of a region doc.
Usage: python3 .docs/gen_zones.py .docs/zones/tatar_sunda.md   (run from the project root)"""
import re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + "/"
DOC = sys.argv[1]
txt = open(DOC).read()
FLOOR = {"path": ",", "grass": ".", "tea terrace": "t", "floor": "_"}

def gd_props(p):  # quoted strings are skipped, so a cond like "!flag:a,flag:b" is left alone
    def fix(m):
        if m.group(1):
            return m.group(1)
        return m.group(2) + ' "%s": ' % m.group(3) if m.group(3) else '"%s"' % m.group(4)
    p = re.sub(r'("(?:[^"\\]|\\.)*")|([{,])\s*(\w+):\s*|(res://[\w/.]+)', fix, p)   # keys, bare paths
    return p.replace('{ "', '{"')

for m in re.finditer(r"^## Area \d+: ([a-z]+_\w+).*?(?=^## |\Z)", txt, re.S | re.M):
    aid, sec = m.group(1), m.group(0)
    rows = re.search(r"### Map\n+```\n(.*?)\n```", sec, re.S).group(1).split("\n")
    spots = []
    for ln in re.search(r"### Legend\n(.*?)(?=\n###|\Z)", sec, re.S).group(1).split("\n"):
        if not ln.startswith("| `"):
            continue
        c = [x.strip() for x in ln.strip().strip("|").split(" | ")]
        ch, what, scene, props, floor = c[0].strip("`"), c[1], c[2].strip("`"), c[3].strip("`"), c[4]
        spots.append('\t"%s": {"scene": "%s", "props": %s, "tile": "%s"},   # %s'
                     % (ch.replace("\\", "\\\\").replace('"', '\\"'), scene, gd_props(props), FLOOR[floor], what))
    title = sec.split("\n")[0]
    sc = re.search(r"^Scale: (\d+)", sec, re.M)   # towns are drawn at 1x on bigger maps (architecture.md 9, Phase 6c)
    base = "zones/%s_base.gd" % aid   # hand-written code for this area lives there and survives a re-run
    out = ['extends "res://%s"' % base if os.path.exists(ROOT + base) else 'extends Zone', '## %s. Generated by .docs/gen_zones.py from %s: change the doc and re-run, not this file.' % (title.lstrip("# "), os.path.relpath(DOC, ROOT)),
           '', 'const MAP := [']
    out += ['\t"%s",' % r for r in rows]
    out += [']', '', 'const SPOTS := {'] + spots + ['}', '', '',
            'func map() -> PackedStringArray:', '\treturn PackedStringArray(MAP)', '', '',
            'func spots() -> Dictionary:', '\treturn SPOTS', '']
    if sc:
        out += ['', 'func area_scale() -> int:', '\treturn %s' % sc.group(1), '']
    open(ROOT + "zones/%s.gd" % aid, "w").write("\n".join(out))
    name = "".join(w.capitalize() for w in aid.split("_"))
    open(ROOT + "zones/%s.tscn" % aid, "w").write(
        '[gd_scene format=3]\n\n[ext_resource type="Script" path="res://zones/%s.gd" id="1"]\n\n'
        '[node name="%s" type="Node2D"]\nscript = ExtResource("1")\nzone_id = "%s"\n' % (aid, name, aid))
    print(aid, len(rows[0]), "x", len(rows), len(spots), "spots")
